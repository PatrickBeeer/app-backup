const COVER_PROMPT_TEMPLATE = `生成一张原创的小红书竖版封面底图，用于标题“{title}”。
内容要求：{brief}
参考爆款的视觉方法：{visual_reference}

内容优先级必须严格遵守：新标题 > 用户内容要求 > 参考爆款视觉方法。先从新标题和用户要求中识别目标城市、地点、人物、产品、季节和事件，并只生成这些新内容。参考爆款中出现的城市、地标、人物、服装、道具、产品、食物、建筑和背景都属于禁止复用的原素材，不得出现在新画面中。

例如：原封面是青岛海景＋文字，而新标题或用户要求是重庆，必须生成可识别的重庆山城、江景、坡道、城市建筑等重庆相关新场景，绝不能继续生成青岛、海滩、海岸线或原图相似景观。只能继承“城市风景照片＋标题”的媒介类型、景别、留白和文字层级。

必须严格保持参考信息中的封面类型：landscape_text 必须生成风景照片，person_text 必须生成人物场景，product_text 必须生成产品实拍，food_text 必须生成食物场景，space_text 必须生成空间场景，other_photo_text 必须生成对应照片主体；禁止把任何 photo_text 类型改成纯色、抽象背景或纯文字海报。

画面必须真实承接新标题的主题、对象和使用场景，第一眼能看懂内容在讲什么。借鉴参考爆款的配色倾向、景别、主体位置、留白比例和视觉节奏，但不得复制原图、人物、产品摆放、标志性构图或其他可识别元素。画面要像自然生活分享或编辑摄影，不像广告素材。

必须为竖版构图，主体清晰，在上方或中部预留足够干净空间供程序后续叠加中文标题。禁止生成任何文字、字母、数字、品牌 Logo、水印、平台界面、圆圈、圆点阵列、气泡、贴纸或圆形装饰。`;

export function coverPrompt(title: string, brief: string, visualReference: string): string {
  return COVER_PROMPT_TEMPLATE.replace('{title}', title)
    .replace(
      '{brief}',
      brief.trim() || '未补充，以标题语义为准',
    )
    .replace(
      '{visual_reference}',
      visualReference.trim() || '无明确参考，采用干净自然的小红书生活方式摄影',
    );
}

